const uint8_t *Display::Glyph(char c)
{
    if(c >= '0' && c <= '9')
        return kDigits[c - '0'];
    if(c >= 'A' && c <= 'Z')
        return kUpper[c - 'A'];
    if(c >= 'a' && c <= 'z')
        return kUpper[c - 'a'];
    for(const auto &p : kPunct)
        if((char)p[0] == c)
            return p + 1;
    return kBlank;
}

